"""Generates App/js/words-everyday.js from scripts/everyday_words_raw.py,
looking up pronunciations via the shared generate_pronunciations module.
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from everyday_words_raw import EVERYDAY_WORDS
from generate_pronunciations import pronounce

# Manual overrides for words the CMU dictionary doesn't cover (verified during
# planning: ~0.6% miss rate, e.g. modern/informal words).
PRONUNCIATION_OVERRIDES = {
    "clingy": "KLING-ee",
    "influencer": "IN-floo-en-ser",
}


def make_id(word):
    return word.lower().replace(" ", "-")


def build_entries():
    entries = []
    missing_pronunciations = []
    for raw in EVERYDAY_WORDS:
        word = raw["word"]
        pron = pronounce(word, overrides=PRONUNCIATION_OVERRIDES)
        if pron is None:
            missing_pronunciations.append(word)
            pron = "(pronunciation unavailable)"
        entries.append({
            "id": make_id(word),
            "word": word,
            "pronunciation": pron,
            "deck": "everyday",
            "meanings": raw["meanings"],
        })
    return entries, missing_pronunciations


def main():
    entries, missing = build_entries()
    if missing:
        print(f"WARNING: {len(missing)} words missing pronunciations: {missing}")
        print("Add manual entries to PRONUNCIATION_OVERRIDES in this script and re-run.")

    output_path = Path(__file__).parent.parent / "App" / "js" / "words-everyday.js"
    js_content = (
        "// Generated by scripts/generate_everyday_deck.py — do not hand-edit.\n"
        "export const wordsEveryday = "
        + json.dumps(entries, indent=2, ensure_ascii=False)
        + ";\n"
    )
    output_path.write_text(js_content, encoding="utf-8")
    print(f"Wrote {len(entries)} entries to {output_path}")


if __name__ == "__main__":
    main()
