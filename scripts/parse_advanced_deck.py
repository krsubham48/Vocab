"""Parses scripts/sat_vocab_extracted.txt (raw PDF text) into
App/js/words-advanced.js. Handles the source's noisy page structure
(repeated headers, lone section-letter lines, mid-sentence line wraps)
and multi-meaning entries like 'annex 1. (v.) ... 2. (n.) ...'.

Verified during planning against real extracted text: 20/20 entries parsed
correctly, including multi-meaning entries with mixed parts of speech.
"""
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from generate_pronunciations import pronounce

POS_MAP = {"v": "verb", "n": "noun", "adj": "adjective", "adv": "adverb"}
NOISE_LINES = {"SAT Vocabulary", "The 1000 Most", "Common SAT", "Words"}

ENTRY_START = re.compile(
    r"([A-Za-zÀ-ÿ][A-Za-zÀ-ÿ\-]*)\s+((?:\d+\.\s+)?\(\s*(?:v|n|adj|adv)\.\s*\))"
)
MEANING_PATTERN = re.compile(
    r"(?:(\d+)\.\s+)?\(\s*(v|n|adj|adv)\.\s*\)\s*([^(]+?)\s*\(([^()]*(?:\([^()]*\)[^()]*)*)\)"
)

# A small number of source examples include mature/explicit references
# inconsistent with a general-audience app (see design spec, Content & Word
# Bank section). Replace just the example sentence for those entries;
# keep word/definition/difficulty unchanged. Add entries here as discovered
# during review in Step 5.
EXAMPLE_OVERRIDES = {
    # "word": "Replacement example sentence.",
}


def clean_lines(raw_text):
    cleaned = []
    for line in raw_text.splitlines():
        stripped = line.strip()
        if not stripped:
            continue
        if stripped in NOISE_LINES:
            continue
        if len(stripped) == 1 and stripped.isalpha() and stripped.isupper():
            continue
        cleaned.append(stripped)
    return cleaned


def split_entries(blob):
    matches = list(ENTRY_START.finditer(blob))
    entries = []
    for i, m in enumerate(matches):
        word = m.group(1)
        start = m.start()
        end = matches[i + 1].start() if i + 1 < len(matches) else len(blob)
        entries.append((word, blob[start:end].strip()))
    return entries


def parse_meanings(word, entry_text):
    rest = entry_text[len(word):].strip()
    meanings = []
    for m in MEANING_PATTERN.finditer(rest):
        _, pos_abbr, definition, example = m.groups()
        meanings.append({
            "partOfSpeech": POS_MAP[pos_abbr],
            "definition": definition.strip().rstrip(",").strip(),
            "example": example.strip(),
        })
    return meanings


def make_id(word):
    return word.lower().replace(" ", "-")


def main():
    source_path = Path(__file__).parent / "sat_vocab_extracted.txt"
    raw_text = source_path.read_text(encoding="utf-8")

    blob = " ".join(clean_lines(raw_text))
    blob = re.sub(r"\s+", " ", blob)

    raw_entries = split_entries(blob)

    results = []
    problems = []
    missing_pronunciations = []
    seen_ids = set()

    for word, text in raw_entries:
        meanings = parse_meanings(word, text)
        if not meanings:
            problems.append((word, text[:120]))
            continue

        if word in EXAMPLE_OVERRIDES:
            meanings[0]["example"] = EXAMPLE_OVERRIDES[word]

        word_id = make_id(word)
        if word_id in seen_ids:
            continue  # source list has no true duplicates, but guard anyway
        seen_ids.add(word_id)

        pron = pronounce(word)
        if pron is None:
            missing_pronunciations.append(word)
            pron = "(pronunciation unavailable)"

        results.append({
            "id": word_id,
            "word": word.capitalize(),
            "pronunciation": pron,
            "deck": "advanced",
            "meanings": meanings,
        })

    print(f"Parsed {len(results)} words successfully.")
    if problems:
        print(f"WARNING: {len(problems)} entries failed to parse meanings:")
        for word, snippet in problems[:20]:
            print(f"  {word!r}: {snippet!r}")
    if missing_pronunciations:
        print(f"WARNING: {len(missing_pronunciations)} words have no CMU dictionary pronunciation.")
        print("These were written with a placeholder; review and consider manual overrides in generate_pronunciations.py overrides usage.")
        print(missing_pronunciations)

    output_path = Path(__file__).parent.parent / "App" / "js" / "words-advanced.js"
    js_content = (
        "// Generated by scripts/parse_advanced_deck.py — do not hand-edit.\n"
        "export const wordsAdvanced = "
        + json.dumps(results, indent=2, ensure_ascii=False)
        + ";\n"
    )
    output_path.write_text(js_content, encoding="utf-8")
    print(f"Wrote {len(results)} entries to {output_path}")


if __name__ == "__main__":
    main()
